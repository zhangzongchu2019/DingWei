-- 仅新表/索引；与旧UUID任务、PG身份表和旧派单outbox分离。
CREATE TABLE r10_task_lock (
 provider TEXT NOT NULL,
 instance TEXT NOT NULL,
 repository_id TEXT NOT NULL,
 change_directory TEXT NOT NULL,
 task_id TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('active','released','expired','handed_off')),
 generation INTEGER NOT NULL CHECK(generation>0),
 lease_token TEXT NOT NULL UNIQUE CHECK(length(lease_token)=64),
 holder_agent_id TEXT NOT NULL,
 holder_owner_lc TEXT NOT NULL,
 assigned_by_user_id_lc TEXT NOT NULL,
 authorization_group_code TEXT NOT NULL,
 commit_sha TEXT NOT NULL,
 tasks_blob_sha TEXT NOT NULL,
 task_line INTEGER NOT NULL CHECK(task_line>0),
 granted_at_utc TEXT NOT NULL,
 expires_at_utc TEXT NOT NULL,
 last_renewed_at_utc TEXT NOT NULL,
 updated_at_utc TEXT NOT NULL,
 monitor_ref TEXT NOT NULL,
 pull_request_id INTEGER NOT NULL CHECK(pull_request_id>=0),
 pr_dimension TEXT NOT NULL CHECK(pr_dimension IN ('pr_not_opened','readable','comparison_unknown')),
 pr_head_sha TEXT NOT NULL DEFAULT '',
 pr_remote_state TEXT NOT NULL DEFAULT '',
 pr_base_ref TEXT NOT NULL DEFAULT '',
 pr_head_ref TEXT NOT NULL DEFAULT '',
 pr_updated_at_utc TEXT NOT NULL DEFAULT '',
 comparison_state TEXT NOT NULL CHECK(comparison_state IN ('clean','needs_sync','comparison_unknown')),
 observed_commit_sha TEXT NOT NULL DEFAULT '',
 last_attempt_at_utc TEXT NOT NULL DEFAULT '',
 last_checked_at_utc TEXT NOT NULL DEFAULT '',
 comparison_error_class TEXT NOT NULL DEFAULT '',
 handoff_json TEXT NOT NULL DEFAULT '{}',
 sync_required INTEGER NOT NULL DEFAULT 0 CHECK(sync_required IN (0,1)),
 CHECK((pull_request_id=0 AND pr_dimension='pr_not_opened') OR (pull_request_id>0 AND pr_dimension IN ('readable','comparison_unknown'))),
 PRIMARY KEY(provider,instance,repository_id,change_directory,task_id)
);
CREATE INDEX r10_task_lock_expiry ON r10_task_lock(state,expires_at_utc);
CREATE INDEX r10_task_lock_monitor ON r10_task_lock(state,provider,instance,repository_id,monitor_ref,pull_request_id);
CREATE TABLE r10_task_lock_operation (
 operation_id TEXT PRIMARY KEY,
 provider TEXT NOT NULL,
 instance TEXT NOT NULL,
 repository_id TEXT NOT NULL,
 change_directory TEXT NOT NULL,
 task_id TEXT NOT NULL,
 operation_kind TEXT NOT NULL,
 request_sha256 TEXT NOT NULL,
 actor_kind TEXT NOT NULL,
 actor_user_id_lc TEXT NOT NULL,
 actor_agent_id TEXT NOT NULL,
 actor_owner_lc TEXT NOT NULL,
 expected_generation INTEGER NOT NULL,
 result_generation INTEGER NOT NULL,
 outcome TEXT NOT NULL,
 result_json TEXT NOT NULL,
 created_at_utc TEXT NOT NULL,
 completed_at_utc TEXT NOT NULL
);
CREATE TABLE r10_task_lock_event (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 operation_id TEXT NOT NULL,
 provider TEXT NOT NULL,
 instance TEXT NOT NULL,
 repository_id TEXT NOT NULL,
 change_directory TEXT NOT NULL,
 task_id TEXT NOT NULL,
 generation INTEGER NOT NULL,
 event_type TEXT NOT NULL,
 actor_kind TEXT NOT NULL,
 actor_user_id_lc TEXT NOT NULL,
 actor_agent_id TEXT NOT NULL,
 actor_owner_lc TEXT NOT NULL,
 at_utc TEXT NOT NULL,
 detail TEXT NOT NULL
);
CREATE INDEX r10_task_lock_event_history ON r10_task_lock_event(provider,instance,repository_id,change_directory,task_id,id);
CREATE TABLE r10_task_lock_outbox (
 id TEXT PRIMARY KEY,
 operation_id TEXT NOT NULL,
 provider TEXT NOT NULL,
 instance TEXT NOT NULL,
 repository_id TEXT NOT NULL,
 change_directory TEXT NOT NULL,
 task_id TEXT NOT NULL,
 generation INTEGER NOT NULL,
 recipient_kind TEXT NOT NULL CHECK(recipient_kind IN ('agent','user')),
 recipient_id TEXT NOT NULL,
 recipient_owner_lc TEXT NOT NULL,
 event_type TEXT NOT NULL,
 delivery_state TEXT NOT NULL CHECK(delivery_state IN ('pending','attempting','queued','available','unknown','superseded')),
 source_envelope_id TEXT NOT NULL UNIQUE,
 delivery_id TEXT NOT NULL DEFAULT '',
 created_at_utc TEXT NOT NULL,
 completed_at_utc TEXT NOT NULL DEFAULT '',
 reason TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX r10_task_lock_outbox_unique ON r10_task_lock_outbox(provider,instance,repository_id,change_directory,task_id,generation,event_type,recipient_kind,recipient_id);
CREATE INDEX r10_task_lock_outbox_pending ON r10_task_lock_outbox(delivery_state,created_at_utc,id);
